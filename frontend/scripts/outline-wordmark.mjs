// Outlines the wordmark ("break" in Unbounded Regular, "FAST" in Unbounded ExtraBold) into SVG paths
// and writes src/brand/wordmark.js, so the app draws the name without loading a font.
// Run by `npm run icons`; the fonts are dev-only (@fontsource/unbounded, SIL OFL 1.1).
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const fontFile = (weight) => require.resolve(`@fontsource/unbounded/files/unbounded-latin-${weight}-normal.woff`)
const load = (weight) => {
  const buf = readFileSync(fontFile(weight))
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
}

export function outlineWordmark({ first = 'break', second = 'FAST', size = 100 } = {}) {
  const regular = load(400)
  const bold = load(800)
  const baseline = size
  const firstPath = regular.getPath(first, 0, baseline, size)
  const space = regular.getAdvanceWidth(' ', size)
  const secondX = regular.getAdvanceWidth(first, size) + space
  const secondPath = bold.getPath(second, secondX, baseline, size)
  const a = firstPath.getBoundingBox()
  const b = secondPath.getBoundingBox()
  const box = { x: Math.min(a.x1, b.x1), y: Math.min(a.y1, b.y1), x2: Math.max(a.x2, b.x2), y2: Math.max(a.y2, b.y2) }
  // Move the drawing to 0,0 so its viewBox is exactly what's drawn
  const shift = (path) => {
    path.commands.forEach((c) => {
      for (const k of ['x', 'x1', 'x2']) if (k in c) c[k] -= box.x
      for (const k of ['y', 'y1', 'y2']) if (k in c) c[k] -= box.y
    })
    return path.toPathData(2)
  }
  return {
    width: +(box.x2 - box.x).toFixed(2),
    height: +(box.y2 - box.y).toFixed(2),
    first: shift(firstPath),
    second: shift(secondPath),
  }
}

export function writeWordmark() {
  const w = outlineWordmark()
  const out = '// Generated by scripts/outline-wordmark.mjs (`npm run icons`): do not edit by hand.\n'
    + '// The wordmark in Unbounded (SIL OFL 1.1): `first` is "break" (Regular), `second` is "FAST" (ExtraBold).\n'
    + `export const WORDMARK = ${JSON.stringify(w, null, 2)}\n`
  writeFileSync(join(root, 'src', 'brand', 'wordmark.js'), out)
  console.log('wrote src/brand/wordmark.js')
}
